static uint16_t Comm_ReadID(void)
{
    uint16_t high, low;
    LCD_WR_REG(0xD3);
    (void)LCD_RD_DATA(); /* dummy */
    (void)LCD_RD_DATA(); /* IC??,???00 */
    high = LCD_RD_DATA() & 0xFFU;
    low  = LCD_RD_DATA() & 0xFFU;
    return (uint16_t)((high << 8) | low);
}

static uint8_t Comm_ReadMADCTL(void)
{
    LCD_WR_REG(0x0B);
    (void)LCD_RD_DATA(); /* dummy */
    return (uint8_t)(LCD_RD_DATA() & 0xFFU);
}

static void Comm_WriteMADCTL(uint8_t value)
{
    LCD_WR_REG(0x36);
    LCD_WR_DATA((uint16_t)(value & 0xFCU));
}

static void Comm_TestWrite(void)
{
    static const uint8_t pattern[4] = {0x08, 0x48, 0x88, 0x28};
    uint8_t original = Comm_ReadMADCTL() & 0xFCU;
    uint8_t passed = 1;
    uint32_t i;

    for (i = 0; i < 4; ++i) {
        Comm_WriteMADCTL(pattern[i]);
        comm_readback[i] = Comm_ReadMADCTL();
        if ((comm_readback[i] & 0xFCU) != pattern[i]) {
            passed = 0;
        }
    }

    /* ???????????;????????????? */
    Comm_WriteMADCTL(original);
    if ((Comm_ReadMADCTL() & 0xFCU) != original) passed = 0;
    comm_write_ok = passed;
}
